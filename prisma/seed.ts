async function main() {
  let categories = 0;
  let articles = 0;

  for (const category of CATEGORIES) {
    const { articles: rows = [], ...data } = category;

    await prisma.category.upsert({
      where: { slug: data.slug },
      create: data,
      update: { ...data },
      select: { id: true },
    });
    categories += 1;

    const parent = await prisma.category.findUnique({
      where: { slug: data.slug },
      select: { id: true },
    });
    if (!parent) continue;

    for (const article of rows) {
      await prisma.article.upsert({
        where: { slug: article.slug },
        create: { ...article, categoryId: parent.id },
        // Body is overwritten deliberately: the owner edits articles through the
        // admin panel, and a re-seed must not silently revert a correction.
        update: { ...article, categoryId: parent.id },
        select: { id: true },
      });
      articles += 1;
    }
  }

  const total = await prisma.category.count({ where: { isActive: true } });
  console.log(`  श्रेणियाँ: ${categories} (सक्रिय ${total})`);
  console.log(`  लेख: ${articles}`);
  console.log('\nनया लेख जोड़ना हो तो prisma/seed.ts में जोड़ें, या /admin से।');
}

main()
