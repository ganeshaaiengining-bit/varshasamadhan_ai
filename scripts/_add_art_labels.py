path = "src/content/i18n.ts"
text = io.open(path, encoding="utf-8").read()
lines = text.split("\n")

already = set(re.findall(r"'(art\.[A-Za-z0-9._-]+)':", text))
current = None
added = 0
for i, line in enumerate(lines):
    m = re.match(r"^const (\w+)", line)
    if m:
        current = m.group(1)
    if current not in TABLE.values() or "home.metaTitle" not in line:
        continue
    code = [k for k, v in TABLE.items() if v == current][0]
    block = []
    for slug, parts in ART.items():
        for part in ("title", "summary"):
            key = "art.%s.%s" % (slug, part)
            if key in already:
                continue
            # Escape the apostrophe — see the note in _add_cat_labels.py.
            value = parts[part][code].replace("\\", "").replace("'", "\\'")
            block.append("  '%s': '%s'," % (key, value))
            added += 1
    lines[i + 1 : i + 1] = block

io.open(path, "w", encoding="utf-8", newline="").write("\n".join(lines))
print("article labels added:", added)
