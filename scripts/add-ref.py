def esc(value: str) -> str:
    return value.replace("\\", "\\\\").replace("'", "\\'")


def set_key(source: str, table: str, key: str, value: str) -> tuple[str, bool]:
    start = re.search(r"const " + table + r"[^=]*=\s*\{", source)
    if not start:
        raise SystemExit(f"table {table} not found")
    end = source.index("\n};", start.end())
    body = source[start.end():end]

    pattern = re.compile(r"( *)'" + re.escape(key) + r"':\s*'(?:[^'\\]|\\.)*',")
    line = f"'{key}': '{esc(value)}',"

    if pattern.search(body):
        new_body, count = pattern.subn(lambda m: m.group(1) + line, body)
        if count != 1:
            raise SystemExit(f"{table}.{key} appears {count} times")
        return source[: start.end()] + new_body + source[end:], True

    return source[: start.end()] + body.rstrip() + "\n\n  " + line + "\n" + source[end:], False


def read_hindi() -> dict[str, str]:
    """The HINDI table out of i18n.ts, which is the source these come from."""
    source = io.open(FILE, encoding="utf-8").read()
    start = re.search(r"const HINDI[^=]*=\s*\{", source)
    body = source[start.end():source.index("\n};", start.end())]
    return dict(re.findall(r"'([^']+)'\s*:\s*'((?:[^'\\]|\\.)*)'", body))


def ascii_digits(value: str) -> str:
    """Replace any non-ASCII decimal digit with its ASCII equivalent.

    Written because the Bengali translation of ref.helpline1 came out as
    "১১২ নম্বরে" and the guard below caught it. That matters more than it looks:
    an Indian phone keypad is labelled 0-9 in Western digits, and ১১২ does not
    dial 112. For an emergency line, transliteration is the difference between
    reaching help and not. ASCII digits are also entirely normal in Bengali,
    Telugu and Malayalam text, so nothing is lost by using them everywhere.
    """
    return "".join(
        chr(ord(ch) - 0x0660 + 0x30) if 0x06F0 <= ord(ch) <= 0x06F9
        else chr(ord(ch) - 0x0966 + 0x30) if 0x0966 <= ord(ch) <= 0x096F
        else chr(ord(ch) - 0x09E6 + 0x30) if 0x09E6 <= ord(ch) <= 0x09EF
        else chr(ord(ch) - 0x0BE6 + 0x30) if 0x0BE6 <= ord(ch) <= 0x0BEF
        else chr(ord(ch) - 0x0C66 + 0x30) if 0x0C66 <= ord(ch) <= 0x0C6F
        else chr(ord(ch) - 0x0CE6 + 0x30) if 0x0CE6 <= ord(ch) <= 0x0CEF
        else chr(ord(ch) - 0x0D66 + 0x30) if 0x0D66 <= ord(ch) <= 0x0D6F
        else chr(ord(ch) - 0x0E50 + 0x30) if 0x0E50 <= ord(ch) <= 0x0E59
        else chr(ord(ch) - 0x0ED0 + 0x30) if 0x0ED0 <= ord(ch) <= 0x0ED9
        else chr(ord(ch) - 0x0F20 + 0x30) if 0x0F20 <= ord(ch) <= 0x0F29
        else ch
        for ch in value
    )


def main() -> int:
    source = io.open(FILE, encoding="utf-8").read()

    # The helpline numbers must survive translation untouched, in digits that a
    # telephone can actually dial.
    #
    # Checked against the Hindi source rather than against a table here, because
    # there is no "hi" entry in T — Hindi is where the strings come from, not
    # something being added. The first version of this guard reached for
    # T["hi"] and died with a KeyError before writing anything, which at least
    # was the harmless way to fail.
    hindi = read_hindi()
    for code in T:
        for key, value in T[code].items():
            value = ascii_digits(value)
            T[code][key] = value

            if not key.startswith("ref.helpline"):
                continue
            for number in re.findall(r"\d{3,5}", hindi.get(key, "")):
                if number not in value:
                    raise SystemExit(
                        f"{code} {key} lost the number {number}. A visitor"
                        f" reading this in {code} would have nothing to dial."
                    )

    count = 0
    for code, table in TABLES:
        for key, value in T[code].items():
            source, existed = set_key(source, table, key, value)
            count += 1
        print(f"  {table:<10} {len(T[code])} keys")

    io.open(FILE, "w", encoding="utf-8", newline="\n").write(source)
    print(f"\n{count} keys x {len(TABLES)} languages = {count * len(TABLES)} strings")
    return 0


